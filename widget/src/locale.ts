export const RTL_LOCALES = ['ar', 'he', 'fa', 'ur'] as const;

export function isRtlLocale(locale: string): boolean {
  return (RTL_LOCALES as readonly string[]).includes(locale.slice(0, 2).toLowerCase());
}

