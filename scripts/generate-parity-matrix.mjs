#!/usr/bin/env node
// Regenerates PARITY.md from every */parity.json (+ docs/parity/*.json for
// out-of-repo SDKs like swift). Source of truth is the JSON; PARITY.md is a
// generated view, never hand-edited.
//
// Usage:
//   node scripts/generate-parity-matrix.mjs           # write PARITY.md
//   node scripts/generate-parity-matrix.mjs --check    # exit 1 if PARITY.md is stale (CI)
//
// No dependencies -- deliberately, so CI needs nothing but a node setup step.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { execSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const MANIFEST_PATHS = [
  'javascript/parity.json',
  'react/parity.json',
  'angular/parity.json',
  'widget/parity.json',
  'dotnet/parity.json',
  'python/parity.json',
  'flutter/parity.json',
  'docs/parity/swift.json',
];

const CHAT_COLS = [
  ['create_conversation', 'Create conv.'],
  ['list_conversations', 'List convs.'],
  ['get_conversation', 'Get conv.'],
  ['close_conversation', 'Close conv.'],
  ['send_message', 'Send msg'],
  ['get_messages', 'Get msgs'],
  ['mark_read', 'Mark read'],
  ['typing_indicator', 'Typing'],
];
const AUTH_COLS = [
  ['login', 'Login'],
  ['register', 'Register'],
  ['refresh', 'Refresh'],
  ['logout', 'Logout'],
  ['password_reset', 'Pw reset'],
  ['email_verification', 'Email verify'],
];
const WIDGET_COLS = [
  ['create', 'Create'],
  ['list', 'List'],
  ['get', 'Get'],
  ['update', 'Update'],
];

function mark(v) {
  if (v === true) return '✅';
  if (v === false) return '❌';
  return '—';
}

function loadManifests() {
  const manifests = [];
  for (const rel of MANIFEST_PATHS) {
    const full = path.join(ROOT, rel);
    if (!existsSync(full)) {
      throw new Error(`Missing manifest: ${rel} (update MANIFEST_PATHS in generate-parity-matrix.mjs if this SDK was removed)`);
    }
    const data = JSON.parse(readFileSync(full, 'utf8'));
    manifests.push({ rel, data });
  }
  return manifests;
}

function tierBadge(tier) {
  return tier === 'active' ? '🟢 active' : tier === 'maintenance' ? '🟡 maintenance' : `⚪ ${tier}`;
}

function section(title, cols, manifests, group) {
  const header = `| SDK | ${cols.map((c) => c[1]).join(' | ')} |`;
  const sep = `|---|${cols.map(() => '---').join('|')}|`;
  const rows = manifests.map(({ data }) => {
    const g = data.capabilities?.[group] ?? {};
    const cells = cols.map(([key]) => mark(g[key]));
    return `| ${data.display_name} | ${cells.join(' | ')} |`;
  });
  return [`### ${title}`, '', header, sep, ...rows, ''].join('\n');
}

function realtimeSection(manifests) {
  const header = '| SDK | Realtime | Protocol |';
  const sep = '|---|---|---|';
  const rows = manifests.map(({ data }) => {
    const rt = data.capabilities?.realtime ?? {};
    return `| ${data.display_name} | ${mark(rt.supported)} | ${rt.protocol ?? '—'} |`;
  });
  return ['### Realtime', '', header, sep, ...rows, ''].join('\n');
}

function platformGapsSection(manifests) {
  const lines = ['### Platform-wide gaps (not per-SDK drift)', ''];
  for (const group of ['rag', 'webhooks']) {
    const anySupported = manifests.some(({ data }) => data.capabilities?.[group]?.supported === true);
    const note = manifests.find(({ data }) => data.capabilities?.[group]?.note)?.data.capabilities[group].note;
    lines.push(`- **${group.toUpperCase()}**: ${anySupported ? 'supported by at least one SDK' : 'supported by **zero** SDKs today'}${note ? ` — ${note}` : ''}`);
  }
  lines.push('');
  return lines.join('\n');
}

function tierTable(manifests) {
  const header = '| SDK | Tier | Last verified | Reason |';
  const sep = '|---|---|---|---|';
  const rows = manifests.map(({ data }) => {
    const reason = (data.tier_reason ?? '').replace(/\|/g, '\\|');
    return `| ${data.display_name} | ${tierBadge(data.tier)} | ${data.last_verified_against_api ?? '—'} | ${reason} |`;
  });
  return [header, sep, ...rows].join('\n');
}

function generate(manifests) {
  const now = new Date().toISOString().slice(0, 10);
  return `<!-- GENERATED FILE. Do not hand-edit. Source of truth is */parity.json (and docs/parity/swift.json for the
     out-of-repo Swift SDK). Regenerate with: node scripts/generate-parity-matrix.mjs -->

# SDK Parity Matrix

What each of the 7 Erghi SDKs actually implements right now, verified against real source code
(not READMEs, not assumptions), and when it was last checked. Regenerated by
\`scripts/generate-parity-matrix.mjs\` from \`*/parity.json\` in this repo plus
\`docs/parity/swift.json\` (a manually-synced reference copy, since Swift lives in
[\`erghi-sdk-swift\`](https://github.com/ErghiPlatform/erghi-sdk-swift), a separate repo).

Regenerated on: ${now}

## Maintenance tier

- 🟢 **active** — gets build effort ahead of parity as the platform's API grows.
- 🟡 **maintenance** — real, working, tested code that keeps getting bug fixes and security
  patches, but is not proactively built ahead of parity. This is a founder-level decision per
  SDK (see \`tier_reason\` below), not something any agent should flip on its own.

${tierTable(manifests)}

## Capability matrix

${section('Auth', AUTH_COLS, manifests, 'auth')}
${section('Chat / conversations', CHAT_COLS, manifests, 'chat')}
${section('Widget management', WIDGET_COLS, manifests, 'widgets')}
${realtimeSection(manifests)}
${platformGapsSection(manifests)}
## How to keep this honest

1. When the platform API changes, update the affected SDK(s)' \`parity.json\` in the same PR —
   flip the capability flag, add \`evidence\` (a \`file:line\`), bump \`last_verified_against_api\`.
2. \`.github/workflows/parity-check.yml\` regenerates this file in CI and fails the build if the
   committed version has drifted from what \`*/parity.json\` says — this file cannot go silently
   stale relative to the manifests it's generated from.
3. The manifests themselves *can* go stale relative to the real code — nothing automatically
   diffs them against \`erghi-conversation-api\`/\`erghi-gateway-api\`/\`erghi-ai-service\` yet. Treat
   \`last_verified_against_api\` as a trust signal: a manifest older than a few weeks deserves a
   re-read before you rely on it, the same way any other doc in this workspace does.
4. Swift (\`docs/parity/swift.json\`) is the one manifest this repo's CI cannot verify at all,
   because the code it describes lives in a different repo. Whoever changes
   \`erghi-sdk-swift\`'s capability surface is responsible for updating this copy too.

Per-package detail, evidence, and freeform notes live in each \`parity.json\` — this file is a
skimmable summary, not the full record.
`;
}

function main() {
  const manifests = loadManifests();
  for (const { rel, data } of manifests) {
    if (!data.sdk_id || !data.display_name || !data.tier || !data.capabilities) {
      throw new Error(`${rel}: missing one of sdk_id/display_name/tier/capabilities`);
    }
    if (!['active', 'maintenance'].includes(data.tier)) {
      throw new Error(`${rel}: tier must be 'active' or 'maintenance', got '${data.tier}'`);
    }
  }

  const content = generate(manifests);
  const outPath = path.join(ROOT, 'PARITY.md');
  const check = process.argv.includes('--check');

  if (check) {
    const existing = existsSync(outPath) ? readFileSync(outPath, 'utf8') : '';
    // Ignore the "Regenerated on:" date line so CI doesn't fail purely on day rollover.
    const strip = (s) => s.replace(/^Regenerated on: .*$/m, 'Regenerated on: <date>');
    if (strip(existing) !== strip(content)) {
      console.error('PARITY.md is stale relative to */parity.json. Run: node scripts/generate-parity-matrix.mjs');
      process.exit(1);
    }
    console.log('PARITY.md is up to date.');
    return;
  }

  writeFileSync(outPath, content);
  console.log(`Wrote ${outPath}`);
}

main();
